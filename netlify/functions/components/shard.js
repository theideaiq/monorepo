export const toUnicode = (string) => {
	return Array.from(string).reverse()
	.map(letter => {	
		const hex = letter.codePointAt(0).toString(16);
		return "0000".substring(0, 4 - hex.length) + hex;
	})
	.reduce((pre, curr) =>  pre += curr )
}