    $en$A bank statement is part of applying to some universities. Most don't ask for one when you apply; some do, and others ask after admission, when they issue your visa documents. What you need depends on your situation: will you pay your own way, or are you applying for a scholarship?

## If you'll pay your own way

The university wants to be sure you can cover tuition and living costs for your whole program, so it may ask for a statement showing a large balance, often tens of thousands of dollars depending on the university and country. The visa process usually asks for the same proof.

- **If the person funding you has a bank account:** ask their branch for a statement; they'll hand it over or email it. Many banks also let you download one instantly from their app.
- **If you don't have an account:** open one as soon as you can. It's straightforward in Iraq now, in person or, at some banks, online. See our guide to [bank accounts in Iraq](/club/bank-accounts-in-iraq).
- **Open the account well before you apply** and keep normal activity in it. An account opened on the day you apply can raise questions.
- If a statement really isn't possible, you can write to the university and explain; it's their decision, but a genuine statement is always better.

## If you're applying for a scholarship

If you're applying for a scholarship or financial aid, you probably need it, and the bank statement confirms that need and helps set the size of the award, rather than proving you can pay. Be honest and accurate with every financial detail.

## How do you get considered for scholarships?

Universities do this differently, so check each school's site:

- **Automatically:** many universities consider every applicant for scholarships.
- **By ticking a box:** some ask you to indicate on the application that you want to be considered for aid.
- **With a separate form:** many require an extra financial aid application, such as the College Board's **CSS Profile**, the **ISFAA** (International Student Financial Aid Application) or their own form, sometimes with a different deadline.
- **After admission:** some universities tell you about scholarship programs you can apply for once you're admitted.

Admission and scholarship decisions may arrive together or separately, and many universities offer several scholarships, so read each offer carefully and compare.

## Watch out for

- **Need or merit?** Some awards are need-based, others merit-based. Some US universities also consider international applicants' finances when deciding admission (need-aware).
- **Deadlines:** the financial aid deadline may come before or soon after the application deadline. Add it to [your university list](/club/study-abroad-roadmap).
- **Loans:** student loans for international students are rare and usually expensive. Make a scholarship your first goal.

