    $en$When you apply to a US university, or any program linked to the US, you'll be asked about your grades, and the term GPA comes up a lot. This guide explains what it means and how to present Iraqi grades correctly and honestly.

## What is GPA?

**GPA** stands for Grade Point Average: a single number summarizing your grades over a whole stage of study. US high school is four years, so a high school GPA covers all four; a college GPA covers the bachelor's years.

- It's usually on a **4.0** scale.
- Percentage or letter grades (A, B, C, D, F) are converted to points and averaged, often weighted by subject and credit hours.
- How it's calculated differs between schools, universities and countries.

## School students: don't calculate it yourself

Iraq doesn't use a cumulative GPA at secondary level, and US admissions offices, which see applicants from many systems, understand that. So:

- **Report your grades as they are, out of 100.** On the application, choose a percentage scale (out of 100) and mark it as unweighted.
- **Attach transcripts for your last years:** grades 10, 11 and 12 (4th, 5th and 6th preparatory), or the grades you've finished if you apply before grade 12, translated and stamped by your school.
- **Explain the system in Additional Information** on the Common App: that Iraq has no cumulative GPA, that each year has its own final average, that grade 12 ends with a national ministerial exam (the baccalaureate), and how any number you give was calculated.
- **If a single number is required**, you can give the average of the years you attached, with a clear explanation of how you got it in Additional Information.
- **Your counselor or school representative** sends the school report and describes the grading system from the school's side, so coordinate with them.

The "percentage to GPA" converters all over the internet aren't official and can give misleading numbers. Universities evaluate grades their own way; many recalculate averages themselves or ask for an evaluation from an accredited service such as WES or ECE when they need one.

## University students: get it from your university

If you're a university student or graduate applying for a master's, don't divide your average by 25 or assume 90–100 means A means 4.0. Instead:

- **Request your official transcript from your university**, with a description of its grading system.
- If the foreign university wants a credential evaluation, it will tell you which accredited service to use (such as WES).
- If there's a GPA field, enter your average exactly as it appears on your transcript along with its scale (for example, 85 out of 100), unless the university explicitly asks otherwise.

## Why accuracy matters

Grades are among the most important parts of your application, and a number that doesn't match your official documents raises doubts. Reporting your grades as they are, with a clear explanation, always beats a converted number you can't back up.

