## طلبة المدارس: لا تحسبه بنفسك

العراق لا يستخدم نظام معدل تراكمي في الإعدادية، وهذا مفهوم لدى مكاتب القبول الأمريكية التي تتعامل مع طلبة من أنظمة كثيرة. لذلك:

- **اعرض درجاتك كما هي، من 100.** في الاستمارة اختر أن نظام مدرستك بالنسبة المئوية (من 100) وأن المعدل غير موزون (unweighted).
