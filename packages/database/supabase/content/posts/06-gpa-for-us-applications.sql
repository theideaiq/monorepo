## ما هو الـGPA؟

**GPA** اختصار Grade Point Average، أي المعدل التراكمي: رقم واحد يلخّص درجاتك خلال مرحلة دراسية كاملة. في أمريكا تكون الإعدادية أربع سنوات، فيلخّص الـGPA السنوات الأربع، وفي الجامعة يلخّص سنوات البكالوريوس.

