## Translation in context

Word-for-word translation often misleads you. These tools show words in real sentences:

- **Reverso Context:** shows a word or phrase in translated examples from real texts. It has a phone app too.
- **WordReference:** an accurate dictionary, with forums where translators discuss tricky phrases.
- **DeepL and Google Translate:** for whole sentences, paragraphs and documents. Great for understanding a text quickly.

## Grammar and spelling checks

- **Grammarly:** fixes spelling, grammar and punctuation and suggests clearer wording. The free version is good; the paid one does more.
- **LanguageTool:** a strong alternative that supports many languages, with a browser extension.

Use them to learn: read why each correction is suggested instead of accepting it automatically, and your repeated mistakes will fade over time.

## Meanings, synonyms and expressions

- **Cambridge Dictionary and Oxford Learner's Dictionaries:** clear definitions for learners, with examples and audio pronunciation.
- **Thesaurus.com:** for synonyms and antonyms to vary your writing.
- Look up idioms and phrasal verbs in these dictionaries too; they're among the hardest parts of English for learners.

## Pronunciation

- **YouGlish:** type any word and it plays clips from real YouTube videos of people saying it. A great way to hear words in context and in different accents.
- The dictionaries above have British and American audio.

## Summarizing and reading

If you're facing a long article, summarizing tools or AI assistants can give you a quick idea of what it says. But they can drop important details, so read the original when it matters.

## An important warning: admissions essays

Don't write your admissions essay or personal statement in Arabic and machine-translate it, and don't let a tool write it for you. Universities want your voice, and machine translation produces flat text that can get the meaning wrong. Write in English from the start, use checkers only to review, and ask someone you trust to read your draft.

