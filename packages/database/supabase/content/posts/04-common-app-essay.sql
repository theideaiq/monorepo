- **ابدأ بنفسك لا بالسؤال.** اكتب قائمة بلحظات غيّرتك، أو أشياء تحبها بشغف، أو مشكلات حاولت حلّها. ثم انظر أيّ سؤال يناسب أقوى قصة لديك. السؤال السابع يقبل أي موضوع.
