    $en$If you're applying to US colleges, especially selective ones, you'll need the Common App personal essay. It's often required, and even when it isn't, it strengthens your application. Writing it also builds your English writing, a skill you'll use for the rest of your life.

## What is it?

A personal essay of up to **650 words** that you send with your application to every college you apply to through the [Common App](https://www.commonapp.org). You pick one of seven prompts and use it to tell a story that shows who you are, how you think and what you care about. It isn't a résumé or a list of achievements; it's a window into your character.

## The seven prompts

The Common App publishes its prompts each year, and they have stayed the same in recent cycles. Always check the [official page](https://www.commonapp.org/apply/essay-prompts) before you start:

1. Some students have a background, identity, interest, or talent that is so meaningful they believe their application would be incomplete without it. If this sounds like you, then please share your story.
2. The lessons we take from obstacles we encounter can be fundamental to later success. Recount a time when you faced a challenge, setback, or failure. How did it affect you, and what did you learn from the experience?
3. Reflect on a time when you questioned or challenged a belief or idea. What prompted your thinking? What was the outcome?
4. Reflect on something that someone has done for you that has made you happy or thankful in a surprising way. How has this gratitude affected or motivated you?
5. Discuss an accomplishment, event, or realization that sparked a period of personal growth and a new understanding of yourself or others.
6. Describe a topic, idea, or concept you find so engaging that it makes you lose all track of time. Why does it captivate you? What or who do you turn to when you want to learn more?
7. Share an essay on any topic of your choice. It can be one you've already written, one that responds to a different prompt, or one of your own design.

## Choosing your story

- **Start with yourself, not the prompt.** List moments that changed you, things you're passionate about, or problems you've tried to solve. Then see which prompt fits your strongest story. Prompt 7 takes anything.
- **Small can be powerful.** You don't need a dramatic story. An everyday moment told honestly and in detail reveals more than a big event told in generalities.
- **Keep it about you.** If you write about your grandfather or a teacher, focus on what you learned and how you changed.

## Writing it

- **Open with a scene.** Start with a specific moment that pulls the reader in, not a general statement about life.
- **Show, don't tell.** Instead of "I'm persistent," describe what you did after you failed the first time.
- **Reflect.** The most important part is what the experience meant to you and how it shaped your thinking.
- **Use your own voice.** Write like the best version of how you talk, not with thesaurus words.
- **Revise a lot.** Write several drafts, read them aloud, and get feedback from someone who knows you and someone who doesn't.
- **Respect the limit.** 650 words is the maximum; strong essays usually land between 500 and 650.
- **Start early.** A good essay takes weeks, not a night, and many colleges also ask for short supplemental essays.

