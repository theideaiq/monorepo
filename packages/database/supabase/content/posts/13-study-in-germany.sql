## Is my certificate enough to get in?

The first step is finding out whether your Iraqi secondary certificate qualifies you for direct entry to a German university. You can check in the anabin database and with the admission tool on the DAAD website, and many universities process applications through uni-assist.

In most cases the Iraqi secondary certificate alone isn't enough for direct entry, and the path looks like this:
- **Studienkolleg:** a one-year preparatory course (two semesters) taught in German, focused on the subjects you'll need for your field (medical, technical, economics, and so on).
- **Feststellungsprüfung:** the qualification exam at the end of Studienkolleg. Once you pass it, you can apply to universities.

In some cases, completing a year or more of university study in Iraq in a related subject may open a route to direct admission. The rules differ by state and university, so check your own situation on anabin and the university's website.

## Language

- **German-taught programs:** the majority, especially at bachelor's level. They usually ask for around C1, proven by an accepted test such as DSH (usually level 2), TestDaF (usually 4 in every section), telc Deutsch C1 Hochschule or the Goethe-Zertifikat C1. For Studienkolleg, B1 or B2 is usually enough.
- **English-taught programs:** they exist, mostly at master's level, and ask for IELTS or TOEFL (see our [IELTS guide](/club/ielts-guide)). Learning German is still worth it for daily life and work.

## General requirements for a bachelor's application

- Your secondary certificate and final-year grades, translated and certified.
- Your Feststellungsprüfung result, if required in your case.
- A German language certificate (or English for English-taught programs).
- A motivation letter and CV, and recommendation letters for some programs.

## Fees and costs

- **Tuition:** most public universities charge no tuition, only a relatively modest semester fee that often includes a public transport ticket. Some states are exceptions, such as Baden-Württemberg, which charges tuition to students from outside the EU.
- **Proof of funds:** for the visa you'll usually need a **blocked account (Sperrkonto)** holding a year of living costs; it was about €11,904 a year in 2025. The amount changes yearly, so check it on the German embassy's website before you start.
- **Working while studying:** international students may work part-time within legal limits. Read [how to pay for studying abroad](/club/paying-for-study-abroad).

## Scholarships

The DAAD scholarship database is the best place to start, with funding for bachelor's, master's, PhD and research. German political, religious and private foundations also offer scholarships. Many full scholarships favor applicants who know German, one more reason to start early.

## Why learn German?

After English, German is one of the most useful languages if you're thinking of studying or working in Europe. Germany is one of the world's biggest immigration destinations, with strong demand for engineers, doctors, nurses and developers. German helps you beyond Germany too, in Austria, Switzerland and German companies worldwide.

### How to start

1. **Set your goal:** which level do you need, and by when? (B1 for Studienkolleg, for example, then C1 for university.)
2. **Pick one main resource** and stick with it: an online course, a structured textbook or an accredited institute such as the Goethe-Institut.
3. **Learn the most common words** with each noun's article, because gender is part of the word.
4. **Listen every day:** podcasts, YouTube, music and series with German subtitles.
5. **Speak early:** with a language partner, a tutor or a study group.

### Things you'll notice

- Nouns have three genders: masculine (der), feminine (die) and neuter (das), and you have to learn each word's gender.
- All nouns start with a capital letter.
- Long compound words are common, but they break down into understandable parts.
- The letter ß is unique to German and sounds like ss.
- Plurals come in several forms with no single rule, so learn each plural with its word.

### Useful resources

- **DW Learn German:** free courses from beginner to advanced from Deutsche Welle.
- **Easy German:** a YouTube channel of street interviews with subtitles.
- **Goethe-Institut:** accredited courses and exams, plus free exercises on its website.
- **Arabic-language YouTube channels** teaching German to beginners, handy for grammar explained in your own language.

## Final tips

- Start the language at least a year before you apply.
- Get translations and certifications done early; they take time.
- Budget for every cost, and don't rely on part-time work alone.
