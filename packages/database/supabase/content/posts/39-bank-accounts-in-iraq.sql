## أنواع الحسابات

### الحساب الجاري

الأكثر استخداماً اليوم، لأنه مصمّم للمعاملات اليومية: إيداع وسحب وتحويل في أي وقت، ومن خلاله تدير بطاقتك المصرفية (بطاقة الخصم أو الائتمان).

### حساب التوفير

