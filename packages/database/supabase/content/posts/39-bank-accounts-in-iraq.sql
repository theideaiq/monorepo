## ماذا تحتاج لفتح حساب؟

تختلف الشروط قليلاً بين المصارف، لكنك تحتاج عادة إلى:

- **البطاقة الوطنية الموحّدة**، أو هوية الأحوال المدنية مع شهادة الجنسية إن لم تكن لديك البطاقة الموحّدة.
- **بطاقة السكن**، وقد تُطلب البطاقة التموينية أيضاً.
- **جواز السفر**، خاصة إذا كنت مقيماً من خارج العراق.
- **مبلغ أولي للإيداع** يحدّده المصرف.
