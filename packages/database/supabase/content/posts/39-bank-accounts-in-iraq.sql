## Types of accounts

### Current account

The most widely used, because it's built for everyday transactions: deposit, withdraw and transfer at any time, and manage your bank card (debit or credit) through it.

### Savings account

A tool for managing your savings that helps you keep part of your income away from daily spending. Some banks pay returns or rewards on the money you deposit, depending on each bank's terms.

### Salary account

For people whose employer pays salaries straight into staff accounts. It works much like a current account, and its benefits depend on the bank and its agreement with your employer.

### Securities (investment) account

For anyone interested in investing: used to buy and sell stocks and bonds on the stock exchange, collect dividends and hold securities. It's sometimes linked to your current account.

### Business accounts

If you run a project or company, banking is a core part of your work. A good relationship with your bank helps you build your credit record, get loans to grow, and open salary accounts for your staff. (See also [what is a startup?](/club/startups-explained))

### E-wallets and banking apps

Digital services have changed how we handle money. In Iraq, e-wallets and banking apps such as **ZainCash**, **Qi Card** apps and **FIB** (First Iraqi Bank) let you pay and transfer from your phone. Global services like PayPal and Payoneer vary in what they offer in Iraq, so check what actually works before you rely on one (see [remote work and freelancing](/club/remote-work-and-freelancing)).

## What you need to open an account

Requirements differ slightly between banks, but you'll usually need:

- **The Unified National Card**, or a civil status ID with a nationality certificate if you don't have the unified card.
- **A residence card**; some banks also ask for the ration card.
- **A passport**, especially if you're a resident from outside Iraq.
- **An initial deposit** set by the bank.
- To be at least **18 years old** (some banks offer accounts for younger people under a guardian).

Many banks now let you start the process online in their app, then collect your card at a branch or have it delivered.

## Why open one now?

- Save time, effort and unnecessary paperwork.
- Receive and transfer money easily, inside and outside Iraq.
- Keep your money safer.
- Build a financial record that helps you later.

**A tip if you plan to study abroad:** many universities and visa applications ask for a [bank statement](/club/bank-statement) showing that you, or whoever funds you, can cover the costs. Open the account early, well before you apply, and keep regular activity in it, so it doesn't look like it was opened just for the application. See [our step-by-step application plan](/club/study-abroad-roadmap).

