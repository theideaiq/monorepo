## What the program covers

The program is essentially fully funded, including:

- International flights and local transportation.
- Housing and meals.
- Visa fees and health insurance.
- A reasonable allowance.

High school participants usually stay with volunteer American host families, while university students stay in campus housing or hotels. What you typically pay for yourself is your passport, souvenirs and personal spending.

## How to apply

Applications usually open in the fall (roughly October to November) through an online form. Dates change from year to year, so keep an eye on the official page. The form usually has these sections:

1. **Contact:** your phone number and email.
2. **Family:** details about your family members.
3. **Academics:** your grade and your school or university.
4. **Activities:** volunteering, projects, awards and community work.
5. **Travel:** countries you've visited, if any.
6. **Short answers:** the most important part. Essay questions (answers of up to around 400 words) and multiple-choice questions that show your awareness of your community and who you are.
7. **Documents:** a passport or national ID, and usually a recommendation filled in online by a teacher or supervisor who knows you well, not a relative.
8. **Optional survey:** how you heard about the program; it doesn't affect your chances.

**Tip:** organize your thoughts before you write, check grammar and spelling, and be honest. You'll be asked about your answers in the interview.

## After you apply

This is the usual timeline, and it can change:

- **A verification call:** the team may call some applicants to confirm details.
- **First results:** usually early in the new year, by email.
- **Interviews:** usually in person, with your original documents. They focus on your personality and whether what you say matches your application.
- **Final results:** usually in the spring, sorting applicants into accepted, alternates and not selected.

Once accepted, you start on the visa, housing forms, your health file and the embassy interview.

## How the program runs

Before travel, participants take an online preparation course and attend orientation workshops in Iraq. There are usually several groups: high school students in Arabic, high school students in English, and university students.

In the United States the program lasts about four weeks:

- **Week one:** leadership training and team building.
- **Weeks two and three:** groups spread across different cities. High school students live with host families; university students are placed at universities for academic training and volunteering.
- **The final week:** everyone meets in Washington, DC, to present projects and plan for after they return.

## Back in Iraq

The experience doesn't end when you land. You'll carry out the community project you planned during the program and attend alumni gatherings. Most importantly, you join the IYLEP alumni network, one of the strongest networks for connections and growth in Iraq.

If you're thinking about studying abroad later, this experience makes your application much stronger. See also [the study-abroad roadmap](/club/study-abroad-roadmap) and [online youth exchanges](/club/youth-exchange-programs).

