## Sections

- **Reading and Writing:** about 64 minutes. Short passages, each followed by one question, testing comprehension, vocabulary, grammar and punctuation.
- **Math:** about 70 minutes. Algebra, advanced algebra, data analysis, and basic geometry and trigonometry, all topics from secondary school.

The whole test takes about **2 hours and 14 minutes**, with a short break between sections. Each section has two modules, and the test is **adaptive**: the difficulty of the second module depends on how you did in the first.

- **Calculators** are allowed for the entire Math section. The app has a built-in Desmos calculator, and you can bring an approved one.
- **No essay.** The optional essay has been discontinued.

## Scores

Each section is scored from 200 to 800, for a total of **400 to 1600**. Scores usually come out within a few days of the test in your College Board profile.

## Registration and dates

- Register on the [official SAT site](https://satsuite.collegeboard.org/sat/registration) and pick a test center. There are centers in Iraq, including in Baghdad and the Kurdistan Region, but centers and dates change, so check the site.
- Dates are published by the College Board. Testing in the fall (roughly August to November) leaves time to retake before application deadlines if you need to.
- International fees change; check them when you register.

## Test day

- Install the **Bluebook** app on your laptop or tablet and complete the device check before test day. If you don't have a suitable device, you can request a loaner from the College Board well in advance.
- Bring the **admission ticket** Bluebook generates, a **valid photo ID** (a passport is safest), and your device charged with its charger. Check the College Board's current instructions on printing your ticket.
- Arrive early; your arrival time is on your ticket and is usually in the morning.

## Sending scores

- When you register, and up to **9 days after the test**, you can choose **4 colleges or programs** to receive your scores for free. Pick the top four on [your list](/club/study-abroad-roadmap).
- Sending scores to more schools costs a fee per report; check the current price with the College Board.
- Some universities accept self-reported scores when you apply and ask for the official report after admission; others only accept official reports. Check each school's policy.

## Do I need it if a college is test-optional?

Many colleges are test-optional, though some have gone back to requiring scores. A strong score adds a competitive edge even when it isn't required, especially for international applicants and scholarship candidates. If your score is good, send it.

## How to prepare

1. **Full-length practice tests in Bluebook:** free, official and true to the real thing. Take one first to find your level.
2. **[Khan Academy](https://www.khanacademy.org/test-prep/sat):** free official prep with practice targeted at your weak spots.
3. **Review your mistakes:** after each practice test, understand why you got each question wrong before moving on.
4. **Reading and Writing:** focus on punctuation (commas, colons, dashes), precise and concise phrasing, and read academic English every day.
5. **Math:** learn to use Desmos quickly; it saves a lot of time on equations and graphs.
6. To talk with other test-takers, there's the [r/Sat](https://www.reddit.com/r/Sat) community on Reddit, but always rely on official sources.

