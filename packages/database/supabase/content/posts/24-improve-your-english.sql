## 1. Find your level first

Before any plan, know where you're starting. These free tests measure your level on the Common European Framework (CEFR), from A1 to C2:

- [EF SET](https://www.efset.org): a free online test.
- [The British Council level test](https://learnenglish.britishcouncil.org/online-english-level-test).
- The British Council's EnglishScore app.

Try one or two to be sure, then pick resources that match your level.

## 2. Pick a few resources and stick with them

The most common mistake is collecting dozens of resources and jumping between them. Choose what suits you and commit. Well-known apps and platforms include:

- BBC Learning English, including the short 6 Minute English episodes.
- British Council LearnEnglish, with lessons for every skill and level.
- Duolingo, Memrise, Busuu and Babbel for daily practice.

## 3. Study in this order

### Basics and listening

If you're a beginner, start with listening: short podcasts, pronunciation lessons and conversation books at your level. Listening, then listening, then listening; that's how your brain builds the language.

### Vocabulary

Learn at least the 2,000 most common English words. Learn 10 to 20 new words a day, write about 5 sentences with them, and review them with spaced-repetition apps like Memrise or Anki.

### Speaking

- Talk with native speakers on apps like HelloTalk, or with tutors on platforms like Cambly.
- Record voice notes about a topic you choose, then listen back.
- **Talk to yourself:** pick a topic, look up its vocabulary, prepare your ideas, then hold a full "conversation" with yourself out loud.
- Join conversation groups, including the community at [The IDEA Club](https://t.me/theideaiq_club).

### Films, series and songs

Watch a series or film with English subtitles, then watch it again. The second time you know the story, so your attention goes to the language. Do the same with songs and their lyrics.

### Grammar last

Study grammar, like tenses and verbs, once you have a base of listening and vocabulary, or alongside them. Grammar organizes what you know, but it won't teach you to speak on its own.

