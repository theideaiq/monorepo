## Before you register

- **Seeing your name isn't registering:** if your name appears in the parallel results and you'd rather keep your central (or another) admission, you can usually do so as long as you haven't completed registration.
- **Registering and paying is final:** once you register and pay, your other admissions (central, private, evening and so on) are cancelled, and you can't go back.
- **Compare the full cost:** the fee times the years of study, plus housing, transport and books. Compare it with private universities and with scholarships abroad.

