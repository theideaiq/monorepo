    $en$Parallel admission (*al-muwazi*) is a route into Iraqi public universities that lets you study in the same college's daytime program as everyone else, with an average slightly below the central admission cutoff, in exchange for tuition paid to the university. Parallel seats are added on top of the central admission plan, not taken from it.

## What average do you need?

Each year the Ministry of Higher Education announces admission rules, including how far below the central cutoff parallel students may be. In recent years the rules have looked roughly like this:

- **3 marks** for medicine, dentistry, pharmacy, nursing and health and medical technology.
- **4 marks** for engineering colleges and engineering technical institutes.
- **5 marks** for colleges of science.
- **6 marks** for other fields, including veterinary medicine.

Example: if the pharmacy cutoff in your governorate is 97 and the margin is 3 marks, you could be admitted through parallel with 94 or higher.

These numbers can change, and some are calculated nationally and others per governorate, so read the official admission guide for the year you apply.

## Fees

The ministry sets parallel fees each year for each field. They have been reduced in some years and can usually be paid in installments. For illustration only, these were the fees for the 2021–2022 academic year in Iraqi dinars; they are **not today's fees**:

