## The Tomorrow's Leaders scholarship

A scholarship program funded by the US Department of State (through the Middle East Partnership Initiative, MEPI) for high-achieving, ambitious students from the Middle East and North Africa, to study at partner universities, chiefly AUB, LAU and AUC.

**What it usually covers:** full tuition for the length of the bachelor's degree, housing, health insurance, a living stipend, books, a laptop and flights, plus career workshops, mentoring and training, and sometimes a semester in the US.

**General requirements:**
- A final-year secondary student or recent graduate from an eligible country (Iraq is usually one).
- High grades, leadership qualities and community involvement.
- Good English (TOEFL or whatever the program specifies); some admitted students may get a preparatory English year.
- Official documents: passport, school records and final exam results, and a recommendation letter from a teacher or supervisor.

Dates, detailed requirements and partner universities change from cycle to cycle, so follow the scholarship pages on the partner universities' websites and the US embassy's website.

## How to choose

- **Program:** not every major is available everywhere, and medicine in particular is limited.
- **Accreditation and recognition:** make sure Iraq's Ministry of Higher Education recognizes the university and program, and check the university's academic accreditation.
- **Full cost:** tuition, housing and living, and what available scholarships cover.
- **Language:** everything is taught in English, and many ask for TOEFL, IELTS or the Duolingo English Test. See our [IELTS guide](/club/ielts-guide) and [Duolingo English Test guide](/club/duolingo-english-test).
- **Applying:** many ask for a personal essay similar to the [Common App essay](/club/common-app-essay), and a transcript with your [GPA](/club/gpa-for-us-applications).

Put these universities on a balanced list, as in our [study abroad roadmap](/club/study-abroad-roadmap).

