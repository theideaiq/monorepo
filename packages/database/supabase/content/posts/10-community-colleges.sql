## The qualifications on offer

**Undergraduate:**
- **Diplomas** and **associate degrees**: two to three years, usually at community colleges, and they prepare you for work.
- **Bachelor's degrees**: usually four years at universities.

**Graduate:** master's, then doctorate.

## What are community colleges?

Mostly public colleges offering shorter, practical programs. They're known for being straightforward, easy to get into and much cheaper than universities.

## Why they suit students from Iraq

- **Easier admission:** requirements are far lighter than universities', and many don't ask for standardized tests like the SAT.
- **English courses (ESL):** if you don't have an English test score, or your English is intermediate, many community colleges offer English as a Second Language courses before or alongside your studies. You usually choose this on the application, and some colleges give you a placement test instead of requiring a certificate. Check each college's requirements.
- **Lower costs:** tuition is much lower than at universities and varies by state or province and college, so check current international fees on each college's site.
- **Small classes:** fewer students per class means more personal attention from instructors.
- **Transfer to a university (2+2):** after an associate degree you can transfer to a university and finish your bachelor's in roughly two more years, and many colleges have transfer agreements with state universities. It saves money and time, and you usually don't need new tests. Note: a diploma alone may not be enough to transfer, so choose a transfer or associate program if a bachelor's is your goal.

## The visa: the hardest part

Admission is close to guaranteed, but the visa isn't. The college gives you your visa admission document (such as the I-20 in the US or a letter of acceptance in Canada), and then you have to convince the embassy in your interview that:
- You genuinely intend to study and have a clear academic plan.
- You have enough funding (see our [bank statement guide](/club/bank-statement)).
- You have ties to your home country.

Prepare well for the interview, and be honest and clear.

## Scholarships

Scholarships at community colleges exist but are few, and most come from outside organizations such as charities rather than the college itself. Start with [Scholarships360's community college list](https://scholarships360.org/scholarships/community-college-scholarships/), and look for international student awards on each college's site.

## When to apply

Community colleges usually have no early application round, and admission is often rolling, with deadlines for each term. You'll generally need to wait for your grade 12 results and certificate, then prepare your documents, application and visa paperwork. Leave plenty of time before the term you want, because visa appointments can be delayed.

