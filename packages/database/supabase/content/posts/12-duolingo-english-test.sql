    $en$The Duolingo English Test (DET) was born during the COVID-19 pandemic and is now accepted by thousands of universities worldwide alongside IELTS and TOEFL, with more institutions joining every year. Its biggest advantage: you take it from home, whenever it suits you, without going to a test center.

## How the test works

- **Length:** about one hour, including instructions and a short introduction section (a video and a writing sample) that isn't scored but is sent to universities.
- **Format:** on an internet-connected computer with a webcam and microphone. The test is adaptive: questions get harder or easier based on your answers.
- **Skills:** listening, reading, writing and speaking, through many short question types.
- **Score:** on a scale of 10 to 160, with subscores. Results usually arrive within about two days and are valid for two years.
- **Price:** about US$70 at the time of writing, much cheaper than IELTS or TOEFL. Check the current price on the official site, as it changes.
- **Sending scores:** you can send your results to as many universities as you like, free.

## Does your university accept it?

Before you pay, look up every university on your list on the institutions page of the official site (englishtest.duolingo.com), and check the university's own admissions page too: some programs accept it and some don't, and each sets its own minimum. Many universities ask for roughly 105 to 125, some for more.

## Test-day rules

The test is proctored by video and recording, and any rule break can cancel your score. So:
- Sit in a quiet, well-lit room with nobody else present.
- No earphones, no phone, and no paper or pens on the desk.
- Keep your face and ears visible, and don't look away from the screen for long.
- Don't speak aloud except in the speaking questions.
- Use a stable browser and connection, and test your setup before test day.

Start with the free practice test on the official site; it gives you a realistic idea of the questions and your likely score.

