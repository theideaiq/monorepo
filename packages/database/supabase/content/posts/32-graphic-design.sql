## The elements of design

Every design is built from a few basic elements:

1. **Line.**
2. **Color.**
3. **Shape.**
4. **Texture.**
5. **Space.**
6. **Size.**
7. **Typography:** choosing typefaces and arranging text.

## The principles of design

These guidelines make a design coherent and easy on the eye:

1. **Balance:** how elements are distributed across the page.
2. **Dominance and hierarchy:** making the most important element stand out first.
3. **Proportion:** how the sizes of elements relate to each other.
4. **Contrast:** setting elements apart with color, size or weight.
5. **Rhythm:** how the reader's eye moves through the design.
6. **Unity:** making every element feel part of one piece.

Creativity matters, but so do the academic rules: white space, the rule of thirds, and color theory and how to combine colors.

## Tools

- **Adobe Illustrator:** vector graphics and logos.
- **Adobe Photoshop:** photo editing and raster designs.
- **Figma:** interface design and team collaboration, with a free plan.
- **Affinity Designer and Affinity Photo:** strong alternatives to Adobe's tools.
- **Canva:** quick and easy for posts and presentations.
- **Blender:** free, open-source 3D design.

Don't try to learn everything at once. Start with one or two tools that fit the path you've chosen.

## Motion graphics

Motion graphics are explanatory animations: you take a static, two-dimensional design and add movement and sound effects, such as a logo that spins in an eye-catching way with a signature sound. They're made of a sequence of frames, unlike a static design, which is a single frame.

They're used heavily in marketing because moving visuals are understood faster than text or audio alone and stick in viewers' minds. They're ideal for explaining a product, a service or a complex idea simply.

How to learn them:

1. **Tools:** **Adobe After Effects** is the standard for animation, with **Cinema 4D** or **Blender** for 3D motion and Illustrator for preparing assets. For editing: **Adobe Premiere Pro**, **DaVinci Resolve** (which has a free version) or Final Cut Pro.
2. **Go deeper:** YouTube tutorials and courses on global platforms. The field keeps evolving, so keep following what's new.
3. **Create:** design from your own imagination, and make every piece carry an idea or a piece of information.

## How to become a designer

1. **Choose a path:** visual identity, interfaces, motion or something else.
2. **Master the tools** for your path.
3. **Learn the academic rules** of design.
4. **Train your eye:** follow other designers on Pinterest, Behance and Dribbble, analyze what you like, then recreate it in your own style and colors. The rule: observe, focus, apply.
5. **Practice every day,** even if it's a small piece.
6. **Build a network** with professional designers, learn from them and keep up with trends.

Design depends heavily on your creative vision and on teaching yourself, which is both a challenge and an advantage.

