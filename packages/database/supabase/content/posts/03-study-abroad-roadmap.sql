    $en$Studying abroad is within reach for students in Iraq, but it takes planning that starts months before any deadline. This guide brings the key advice together: building your university list, preparing documents, and having a clear backup plan.

## 1. Start your tests early

Some universities want a standardized test such as the [SAT](/club/sat-guide); others only need an English test like [IELTS](/club/ielts-guide), TOEFL or the [Duolingo English Test](/club/duolingo-english-test), and some accept your SAT English score as proof of language. To keep your options open, plan for both an English test and the SAT if you can. Start studying now and book the earliest date that works, because you may want to retake.

## 2. Build a balanced university list

Your list is a spreadsheet of the universities you're interested in, the program you want at each, the application link and deadline, the tests required, and whether they fund international students. It makes the whole process far easier to track.

- **Pick around 15 universities**, and don't fixate on a single school or country. Spreading across countries raises your chances.
- **Balance them by acceptance rate:**
  - One or two highly selective schools (under 10%).
  - One or two reach schools (10–30%).
  - Several target schools that match your profile (30–50%).
  - Safety schools (over 50%).
- **Think about funding:** a full scholarship at a very selective university can be easier to get than one at a less selective school, because the former usually has more money. Getting admitted is the hard part, though. Focus on universities that genuinely fund international students.

The [Common App](https://www.commonapp.org) lets you apply to hundreds of US colleges with one form, but it doesn't include every university, so check each school's own application route.

## 3. Prepare your documents now

- **Transcripts:** photograph your grade 10, 11 and 12 certificates (4th, 5th and 6th preparatory), get certified translations, and attach both the Arabic and English versions so the stamps and signatures show. A table of your grades per subject and yearly averages, stamped by your school, helps. See our [GPA guide](/club/gpa-for-us-applications) for how to present them.
- **Your school's representative:** most foreign universities won't know your school, so agree with classmates on one spelling of the school's name and one email address, and choose someone in the administration (a counselor or registrar) to send the school report and represent the school.
- **Recommendation letters:** ask teachers who know you well, and give them plenty of time.
- **Passport:** make sure it's valid for at least a year; renew it if not.
- **Certified translations:** translate any required document officially and attach both languages.
- **Bank statement:** some universities ask for proof of funds when you apply or after admission. See our [bank statement guide](/club/bank-statement).
- **Essays:** if you're aiming at selective US colleges, start your [Common App essay](/club/common-app-essay) and each school's supplemental essays early. For the UK, read our [personal statement guide](/club/uk-personal-statement).

## 4. What US and Canadian scholarships usually ask for

- A personal essay (such as the Common App essay) and supplemental essays.
- Transcripts and a school report.
- Letters of recommendation.
- An English test, and SAT scores if required or if they're strong (many colleges are test-optional).
- A list of activities, volunteering and achievements.
- A financial aid application and a bank statement where needed.

Working to pay tuition isn't a realistic plan: international students can only work limited hours. Aim for a full scholarship unless your family can cover the costs. More in our guide to [paying for study abroad](/club/paying-for-study-abroad).

## 5. Expect rejections

You'll apply widely and many schools will say no. That's normal. A rejection doesn't mean you fell short; often other applicants had advantages your circumstances didn't allow. You can apply again next year, and there are many other doors.

## 6. A clear backup plan

1. **Apply to your list (about 15 universities)** across several countries. If you get more than one offer, compare them.
2. **Community colleges in the US and Canada:** easier admission and lower costs, with a path to transfer into a university for your bachelor's. See our [community colleges guide](/club/community-colleges).
3. **Eastern European universities:** relatively strong schools at reasonable cost, such as the [University of Tartu](https://ut.ee/en) in Estonia and [Warsaw University of Technology](https://www.pw.edu.pl) in Poland.
4. **American universities in the region:** strong programs and scholarships such as Tomorrow's Leaders. See [our list](/club/american-universities-in-the-region).
5. **Online degrees:** universities like [University of the People](https://www.uopeople.edu) offer low-cost online degrees with scholarships, and [MIT OpenCourseWare](https://ocw.mit.edu) has free course materials.
6. **Study in Iraq:** at a public or private university (including [parallel admission](/club/parallel-admission)), then apply for a master's abroad after your bachelor's; graduate funding is often easier to find.

