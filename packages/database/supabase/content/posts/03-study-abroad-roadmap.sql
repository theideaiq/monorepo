## 1. ابدأ بالاختبارات مبكراً

بعض الجامعات تطلب اختباراً معيارياً مثل [SAT](/club/sat-guide)، وأخرى تكتفي باختبار لغة مثل [IELTS](/club/ielts-guide) أو TOEFL أو [Duolingo English Test](/club/duolingo-english-test)، وبعضها يقبل درجة الإنجليزي في SAT دليلاً على اللغة. لتبقى خياراتك مفتوحة، خطّط لاختبار لغة واختبار SAT معاً إن استطعت، وابدأ الدراسة الآن لتمتحن في أقرب موعد مناسب، فقد تحتاج إلى إعادة الاختبار.

## 2. ابنِ قائمة جامعات متوازنة

القائمة هي جدول بالجامعات التي تهمّك، والتخصص الذي تريده في كل منها، ورابط التقديم وموعده، والاختبارات المطلوبة، وهل تقدّم منحاً للطلبة الدوليين. هذا الجدول يسهّل عليك المتابعة كثيراً.

- **اختر نحو 15 جامعة** ولا تتعلّق بجامعة أو دولة واحدة. نوّع بين الدول لتزيد فرص القبول.
- **وزّعها حسب نسبة القبول:**
  - جامعة أو اثنتان شديدتا التنافس (نسبة قبول أقل من 10%).
  - جامعة أو اثنتان طموحتان (10–30%).
  - عدة جامعات مناسبة لمستواك (30–50%).
  - جامعات آمنة (أكثر من 50%).
- **انتبه للمنح:** المنحة الكاملة في جامعة نسبة قبولها منخفضة قد تكون أسهل من المنحة الكاملة في جامعة يسهل دخولها، لأن الأولى تملك تمويلاً أكبر، لكن القبول نفسه هو الجزء الأصعب. ركّز على جامعات تقدّم دعماً مالياً حقيقياً للطلبة الدوليين.

منصة [Common App](https://www.commonapp.org) تتيح التقديم على مئات الجامعات الأمريكية من استمارة واحدة، لكنها لا تضم كل الجامعات، فتأكد من طريقة التقديم في موقع كل جامعة.

## 3. جهّز وثائقك من الآن

- **كشوف الدرجات:** صوّر شهادات الصفوف الرابع والخامس والسادس الإعدادي، وترجمها ترجمة معتمدة، وأرفق النسختين العربية والإنجليزية ليظهر الختم والتوقيع. يفضَّل جدول بدرجات كل مادة ومعدل كل سنة مختوم من إدارة المدرسة. اقرأ [دليل المعدل GPA](/club/gpa-for-us-applications) لتعرف كيف تعرض درجاتك.
- **ممثل المدرسة:** معظم الجامعات الأجنبية لا تعرف مدرستك، فاتفق مع زملائك على تهجئة واحدة لاسم المدرسة وبريد إلكتروني واحد، واختاروا شخصاً من الإدارة (مرشداً أو مسجلاً) يرسل تقرير المدرسة ويمثّلها أمام الجامعات.
- **رسائل التوصية:** اطلبها مبكراً من مدرّسين يعرفونك جيداً، وأعطهم وقتاً كافياً.
- **جواز السفر:** تأكد أنه صالح لسنة على الأقل، وجدّده إن قلّت المدة.
- **الترجمة القانونية:** ترجم أي وثيقة مطلوبة ترجمة معتمدة وأرفق اللغتين.
- **الكشف البنكي:** بعض الجامعات تطلب إثباتاً مالياً عند التقديم أو بعد القبول. اقرأ [دليل الكشف البنكي](/club/bank-statement).
- **المقالات:** إن كنت تقدّم على جامعات أمريكية قوية، ابدأ مبكراً بكتابة [مقالة Common App](/club/common-app-essay) والمقالات الإضافية التي تطلبها كل جامعة. وللمملكة المتحدة اقرأ [دليل البيان الشخصي](/club/uk-personal-statement).

## 4. ما تطلبه منح أمريكا وكندا عادة

- مقالة شخصية (مثل مقالة Common App) ومقالات إضافية لكل جامعة.
- كشوف الدرجات وتقرير المدرسة.
- رسائل توصية.
- اختبار لغة، ونتائج SAT إن طُلبت أو إن كانت درجاتك جيدة (كثير من الجامعات تجعله اختيارياً).
- قائمة بالأنشطة والأعمال التطوعية والإنجازات.
- طلب المساعدة المالية والكشف البنكي عند الحاجة.

تذكّر أن العمل لتسديد الرسوم ليس خطة واقعية؛ ساعات العمل المسموحة للطلبة الدوليين محدودة. اجعل هدفك منحة كاملة، إلا إن كانت عائلتك قادرة على تحمّل التكاليف. التفاصيل في [دليل تمويل الدراسة في الخارج](/club/paying-for-study-abroad).

## 5. تقبّل الرفض

ستقدّم كثيراً وسترفضك جامعات كثيرة، وهذا طبيعي. الرفض لا يعني أنك قصّرت؛ غالباً كان لدى متقدّمين آخرين ميزات تنافسية لم تتح لك بسبب ظروفك. يمكنك التقديم مرة أخرى في السنة التالية، والفرص كثيرة.

## 6. خطة بديلة واضحة

1. **قدّم على قائمتك (نحو 15 جامعة)** في دول مختلفة، وإن قُبلت في أكثر من واحدة فقارن بين العروض.
2. **الكليات المجتمعية في أمريكا وكندا:** قبولها أسهل وتكاليفها أقل، ويمكنك الانتقال بعدها إلى جامعة لإكمال البكالوريوس. اقرأ [دليل الكليات المجتمعية](/club/community-colleges).
3. **جامعات أوروبا الشرقية:** فيها جامعات جيدة نسبياً بتكاليف معقولة، مثل [University of Tartu](https://ut.ee/en) في إستونيا و[Warsaw University of Technology](https://www.pw.edu.pl) في بولندا.
4. **الجامعات الأمريكية في المنطقة:** بيئة ومناهج قوية، ومنح مثل Tomorrow's Leaders. راجع [قائمتنا](/club/american-universities-in-the-region).
5. **الدراسة عبر الإنترنت:** جامعات مثل [University of the People](https://www.uopeople.edu) تقدّم شهادات إلكترونية برسوم منخفضة ومنح، ومنصات مثل [MIT OpenCourseWare](https://ocw.mit.edu) تتيح مواد مجانية للتعلم.
6. **الدراسة في العراق:** في جامعة حكومية أو أهلية (ومنها [التعليم الموازي](/club/parallel-admission))، ثم التقديم على دراسات عليا في الخارج بعد البكالوريوس، وهي غالباً أسهل تمويلاً.

