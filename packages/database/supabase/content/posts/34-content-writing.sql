## What is content writing?

Content writing is writing everything that represents a brand and speaks to its audience: blog articles, social media posts, video scripts, podcast outlines, newsletters and website pages. It's the foundation of any online marketing, since even a video needs a script written in advance.

## How it differs from copywriting

[Copywriting](/club/copywriting) aims to sell directly: a few words that push the reader to take a specific action now. Content writing aims to build a long-term relationship with the audience: it teaches, helps and entertains, so people come back and trust the brand when they decide to buy later. Copywriting sells today; content writing builds the trust that makes tomorrow's sale possible.

## Types of content

- **Written:** blog articles, social media posts, and guides like The IDEA Post's.
- **Visual:** scripts for videos, reels and video ads.
- **Audio:** podcast episodes and their outlines.

## The steps behind any piece of content

### 1. Research

The most important step; everything else is built on it. Understand the topic well, gather reliable sources, and get to know your audience: who they are, how they think and what tone suits them. If the content is meant to rank in search engines, research the **keywords** people actually use.

### 2. Write

- Cover the topic from every angle so readers don't need another source.
- Write clearly and simply; avoid jargon and filler.
- Structure it: an introduction that hooks, the body in short paragraphs, and a conclusion that sums up.
- Use the style your audience prefers, not the one you prefer.

### 3. Review

Reread the text after a short break. Fix grammar and spelling, cut what adds nothing and add what's missing. Coordinate with the design team so the text gets visuals that fit.

### 4. Publish and learn

Publish at the right time, then follow how people react: comments, questions and suggestions are the best guide to what to write next.

## Skills you need

- Clean grammar and spelling.
- The ability to review and edit your own work critically.
- Good planning, so the content carries the brand's message.
- Time management to juggle several tasks at once (see [our time management guide](/club/time-management)).
- A grasp of search engine optimization (SEO) basics.

