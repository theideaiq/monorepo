## ما هي كتابة المحتوى؟

كتابة المحتوى (Content Writing) هي كتابة كل ما يمثّل علامة تجارية ويخاطب جمهورها: مقالات المدوّنة، ومنشورات وسائل التواصل، ونصوص الفيديو، وأسئلة البودكاست، والنشرات البريدية، وصفحات الموقع. وهي حجر الأساس في أي تسويق على الإنترنت، فحتى الفيديو يحتاج نصاً مكتوباً مسبقاً.

