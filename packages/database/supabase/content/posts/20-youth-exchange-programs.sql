## The Experiment Digital (TED)

A virtual exchange run by World Learning, formerly called DYLEP. It builds leadership skills, introduces you to volunteering and teaches you how to plan a community project that helps people.

- **Who:** high school students aged roughly 14 to 19 from Iraq, other Arab countries and the United States.
- **Length and commitment:** about eight weeks, usually over the summer, at more than 4 hours a week.
- **How it works:** on a closed learning platform (Canvas), in modules such as digital citizenship, leadership and identity, community initiatives and public narrative. Each module has short assignments, live webinars and weekly Zoom calls with a small "virtual family" and a facilitator.
- **What you gain:** hands-on understanding of leadership, more involvement in civic and volunteer work, and friendships across cultures.
- **Applying:** usually opens early in the year for a few months. They look for participants who are committed, eager to grow and ready to learn from others.

## Leaders of Tomorrow (LoT)

An Iraqi program founded by IYLEP alumni with support from World Learning, connecting young people from around the world online.

- **Who:** high school students (about 14 to 17) and university students (about 18 to 24) from any country, with good spoken and written English.
- **Commitment:** about 4 to 5 hours a week, with reliable internet.
- **How it works:** each cohort has a theme, such as public speaking or teamwork, with dialogue sessions, video calls and online workshops.
- **What you gain:** an understanding of cultural diversity and different viewpoints, plus problem-solving, critical thinking and conflict-resolution skills.
- **Applying:** usually opens in the spring; you may be required not to take part in another exchange at the same time.

## Syrian Youth Empowerment (SYE): Iraq program

A nonprofit that helps high school students in regions affected by instability apply to universities abroad, with a dedicated program for Iraqi students.

- **Who:** students in their final year of high school or recent graduates, with a preparatory track for younger students. Basic English and regular internet access are usually required.
- **How it works:** each student works with a mentor through the application year: building a college list, writing and editing essays and preparing for tests like the SAT, TOEFL and Duolingo, with group sessions and English classes.
- **What you gain:** one-to-one mentoring, study resources and help with application and test fees when available.
- **Applying:** usually opens early in the year, with a form, short essays and an online interview.

## Which one is for you?

- For leadership and a community project: TED or LoT.
- If you're in your final year and aiming for university abroad: SYE, alongside [the study-abroad roadmap](/club/study-abroad-roadmap).

