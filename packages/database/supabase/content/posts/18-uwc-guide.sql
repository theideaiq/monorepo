## What is UWC?

A global education movement made up of around 18 international schools worldwide. Students spend the last two years of secondary school there working toward the **International Baccalaureate Diploma (IB Diploma)**, living alongside students from dozens of countries. The aim is to build responsible people who serve their communities, combining academic study with community service and activities.

## Where are the schools?

Schools are in countries such as the UK, Norway, Germany, Italy, the Netherlands, Bosnia and Herzegovina, Armenia, Canada, the US, Costa Rica, India, China, Japan, Singapore, Thailand, Tanzania and Eswatini. The list can change, so check it on the official site.

## Two ways to apply

A student from Iraq can apply in one of two ways:

### Through a national committee
- **Funding:** a chance at a full or partial scholarship based on financial need.
- **School choice:** the committee nominates you to the most suitable school based on available places.
- **Language:** the application is mostly in English, with Arabic sometimes allowed in parts. Check whether there's an active national committee for Iraq and its conditions in the current cycle.

### Through the Global Selection Programme
- **Funding:** for students who can pay all or most of the costs, which are high (tens of thousands of dollars for two years, depending on the school), with limited financial help in some cases.
- **School choice:** you can state your school preferences.
- **Language:** English only.

**Age:** applicants are usually 16 to 18 at the start of the program. What counts is your age, not your grade, and the limits differ slightly between routes, so check them on the official site.

## How to apply

Applications usually open in late summer or early autumn on the official application portal, and there may be a small application fee. The application typically includes:
- **Personal and academic information:** with your grades from the last two years.
- **Short essays:** questions about your character, values and ability to work with others.
- **Recommendation letters:** from a teacher who knows you well.
- **A short video:** in some cycles, on a topic they set.

Shortlisted candidates then go through selection rounds including **group activities** and **individual interviews**.

## What you study: the IB Diploma

An internationally recognized program in which you study 6 subjects from different groups:
- Your first language and literature.
- An additional language.
- Individuals and societies (social sciences).
- Sciences.
- Mathematics.
- The arts, or an extra subject from another group.

You take 3 subjects at Higher Level (HL) and 3 at Standard Level (SL). Alongside the subjects is **the core**:
- **Extended Essay:** an independent research paper of up to 4,000 words.
- **Theory of Knowledge:** an essay and an oral presentation.
- **Creativity, Activity, Service (CAS):** activities and community service throughout the program.

The maximum score is 45, and the minimum to earn the diploma is 24, with some extra conditions.

## After UWC

UWC graduates stand out to universities. One of the best-known opportunities is the **Davis UWC Scholars** program, which offers need-based scholarships at dozens of partner US universities. The IB Diploma is usually accepted as equivalent to the Iraqi secondary certificate; check the equivalency process with the Ministry of Education.

## Other UWC opportunities

- **Programs for younger students:** some UWC schools accept younger ages through direct application to the school.
- **Short courses:** summer and winter programs of a few weeks for roughly ages 14 to 20.
- **IB Career-related Programme (IBCP):** offered at some schools, with a focus on areas such as climate and business.

## How to prepare

- Start volunteering and community work now; it's a key part of the assessment.
- Build your English, especially writing and speaking: [how to improve your English](/club/improve-your-english).
- Practice writing personal essays; the same skills help later with the [Common App essay](/club/common-app-essay).
- Look at [online youth exchange programs](/club/youth-exchange-programs) and [IYLEP](/club/iylep-guide); they build your record and experience.

