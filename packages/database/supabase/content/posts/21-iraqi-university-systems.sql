    $en$When you start university in Iraq, you'll study under one of three systems. Knowing yours in advance helps you plan your time and understand how your marks are calculated. One caution: if you later want to transfer to a college with a different system, you may have to start again from first year, so ask about transfer rules before you decide.

## The annual system

Close to the school system you're used to:

- You sit first-term exams, a midyear exam, then second-term exams.
- Your marks during the year add up to your coursework mark (*sa'i*), usually out of 50, sometimes out of 40 or 30.
- At the end of the year you sit the final exam for the rest: out of 50 if coursework was out of 50, or out of 60 or 70 if it was lower.
- Some colleges drop the term exams and keep only a midyear and a final.

The final covers the whole syllabus. The upside of this system is that you have several chances during the year to raise your coursework mark before the final.

## The semester system

The year is split into two semesters:

- Each semester has just two exams: a midterm (usually out of 30 or 40) and a final (out of 70 or 60).
- If you fail a subject at the end of a semester, you go straight to the resit (second round) for it, with no chance to make it up during the year.
- You may study the same subject in both semesters with different content, or entirely new subjects in the second.

The pace is faster, so putting things off costs more. Plan your study from week one.

## The module system

Used by some medical colleges, and very different from the other two:

- Instead of separate subjects like anatomy and physiology, you study **body systems**. For the digestive system, for example, you learn its anatomy, function, diseases and drugs together.
- There are usually no monthly or daily quizzes. You're examined on everything in one exam, and if you fail you may resit in the second round.
- Questions are set by a committee rather than one teacher, so you need to study everything, not just what a lecturer emphasized.
- In some colleges a comprehensive exam follows the early years, then the final years are mostly clinical training, followed by another comprehensive exam.

This system is close to how medicine is taught in many countries and demands strong self-discipline. If you're thinking about practicing medicine outside Iraq one day, read [the USMLE guide](/club/usmle-guide).

