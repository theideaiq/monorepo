    $en$How many times have you wanted to learn something new or start an activity, then stopped because there was "no time"? You'll never get more than 24 hours in a day, but how you organize them makes the difference. Here are six tips to help you make the most of your time.

## 1. Know where your time goes

Start by watching yourself for a few days:

- Where does your time go? Your phone, commuting, thinking without doing?
- How long does a particular task take you? Could you do it in less time?
- When in the day are you most energetic and focused?

Peak time differs from person to person: early morning, midday, afternoon or night. Once you know yours, you can put your hardest tasks there.

## 2. Set your priorities

Not all tasks are equal. Put urgent and important tasks first, like an upcoming exam or an essay you need for an application. Do them at the start of your day with full energy, and leave less important tasks for later.

## 3. Write a daily to-do list

Once you know your peak time and priorities, write a to-do list every day, the night before or first thing in the morning, and stick to it as much as you can:

- Put the most important tasks in your peak time.
- Put lighter tasks after them.
- Tick off each task as you finish it.

A list moves tasks out of your head and onto paper, so you're less scattered, and every tick gives you a sense of progress.

## 4. Give every task a deadline

A task without a deadline expands forever and invites procrastination. Set an end time for each task.

Try the Pomodoro technique: work for 25 minutes, rest for 5, repeat 3 or 4 times, then take a longer break of 20 to 30 minutes. It cuts down boredom and the urge to put things off. For more study techniques, read [how to learn faster](/club/learn-faster).

## 5. Leave time to rest

Don't pack your schedule from start to finish; you'll burn out quickly and won't finish what you started. Leave free time to rest and do what you enjoy.

And remember the basics: eat well and sleep well. Focus starts with a rested body, especially around midday when tiredness kicks in.

## 6. Cut out distractions

Your phone, notifications, even side conversations all steal your focus. Getting rid of them is hard at first, but you can do it gradually:

1. Identify the two things that distract you most.
2. Keep away from them during work for two weeks.
3. Add one or two more, and repeat for four weeks.
4. Keep going until most of them are gone.

Try leaving your phone in another room, turning on focus mode or silencing notifications during work sessions.

## The bottom line

Time management is a skill you build with practice, not a talent some people are born with. Start with one step this week and add others gradually. To learn more about the skills employers look for, read [soft skills at work](/club/soft-skills).

