## 2. حدّد أولوياتك

ليست كل المهام متساوية. قدّم المهام العاجلة والمهمة، مثل امتحان قريب، أو مقالة يجب أن تسلّمها لتقديم على فرصة، على غيرها. أنجزها وأنت في بداية يومك وبكامل طاقتك، واترك المهام الأقل أهمية لوقت لاحق.

## 3. اكتب قائمة مهام يومية

بعد أن عرفت وقت ذروتك وأولوياتك، اكتب قائمة مهام (To-Do List) كل يوم، في الليلة السابقة أو أول الصباح، والتزم بها قدر الإمكان:

