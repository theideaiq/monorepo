## Scholarships first

Don't build your plan on working to pay tuition. International students can only work limited hours, and the pay covers part of living costs at best, not university fees. Aim for a full or near-full scholarship unless your family can cover the costs. See our guide to [bank statements and financial aid](/club/bank-statement).

## Work rules in popular destinations

These rules come from each country's visa regulations and change from time to time. What follows was correct at the time of writing; **always check the country's official immigration site and your university's international student office before taking any job.**

- **United States (F-1 visa):** on-campus work up to **20 hours a week** during term and full-time during official breaks. Off-campus work isn't allowed except through study-related programs with official authorization, such as **CPT** (Curricular Practical Training, usually after your first year) and **OPT** (Optional Practical Training, often after graduation).
- **United Kingdom (Student visa):** usually up to **20 hours a week** in term time for degree-level students, more during holidays. Your permitted hours are printed on your residence permit.
- **Canada:** since late 2024, eligible students can work off campus up to **24 hours a week** during term and full-time during scheduled breaks.
- **Germany:** up to **140 full days or 280 half days** a year, with separate rules for student assistant jobs at the university.

Working more than you're allowed, or without permission, can lead to your visa being canceled, expulsion and deportation. Don't risk it.

## Kinds of work

- **On campus:** the library, labs, administrative offices, sports facilities, dining halls, and assisting professors. The easiest start, especially in your first year.
- **Off campus (where allowed):** restaurants, shops and fast-food chains, many of which take applications online.
- **Work in your field:** an internship in your area, such as a computer science student at a tech company through programs like CPT in the US. You gain experience and income together.
- **Pay:** varies a lot by country, city and state, and minimum wages are set locally. Look up the rates for your city.

## Freelancing and tutoring

You might think of freelancing online on platforms like Fiverr and Upwork, or private tutoring. Be careful: in many countries **self-employment isn't allowed on a student visa**, even if the client is abroad. Ask your international student office before you start. Before you leave, though, freelancing from Iraq is a great way to save money and build experience; see our guide to [remote work and freelancing](/club/remote-work-and-freelancing).

## Cutting costs

- Apply to universities with generous scholarships for international students.
- Consider [community colleges](/club/community-colleges) for two years, then transfer to a university.
- Compare living costs between cities; the difference is large.
- Destinations like [Germany](/club/study-in-germany) charge low or no tuition at most public universities, though living costs and proof of funds still apply.

