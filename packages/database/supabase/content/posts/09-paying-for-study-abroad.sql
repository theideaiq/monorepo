## قواعد العمل في أشهر الوجهات

القواعد تحددها قوانين الفيزا في كل بلد، وتتغير من وقت لآخر. ما يلي صحيح وقت كتابة هذا الدليل، **فتحقق دائماً من الموقع الرسمي للهجرة في البلد ومن مكتب الطلبة الدوليين في جامعتك قبل أن تقبل أي عمل.**

