## أنواع العمل المتاحة

- **داخل الحرم الجامعي:** المكتبة، المختبرات، المكاتب الإدارية، المرافق الرياضية، المطاعم الجامعية، ومساعدة الأساتذة. هذه أسهل بداية، خصوصاً في السنة الأولى.
- **خارج الحرم (حيث يُسمح):** المطاعم والمتاجر وسلاسل الوجبات السريعة، وكثير منها يقبل التقديم من موقعه الإلكتروني.
- **عمل مرتبط بتخصصك:** تدريب في شركة ضمن مجالك، مثل طالب علوم الحاسوب في شركة تقنية عبر برامج مثل CPT في أمريكا. يمنحك خبرة ودخلاً معاً.
- **الأجور:** تختلف كثيراً حسب البلد والمدينة والولاية، وللحد الأدنى للأجور قوانين محلية. ابحث عن أجور مدينتك تحديداً.

