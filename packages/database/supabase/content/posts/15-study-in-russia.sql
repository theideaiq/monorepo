## Admission and recognition in Iraq

- Many Russian universities don't require a specific grade for admission, and some set their own entrance tests.
- Iraq's Ministry of Higher Education and Scientific Research, however, sets its own conditions for recognizing your degree, including that the university is on its recognized list and that your secondary-school grade meets a minimum that depends on the field.
- Some internationally ranked universities have different recognition rules.

**Before anything else:** check the list of recognized Russian universities and the grade requirements on the Iraqi Ministry of Higher Education's website, or ask its scholarships department directly. The rules change, and relying on outdated information can cost you years.

## Language of study

- **Russian:** usually cheaper, but requires a **preparatory year** in which you learn Russian and the core subjects of your field in Russian before your degree starts.
- **English:** available at some universities and in some programs (especially medicine), and more expensive than Russian-taught study. Make sure the whole program is in English, not just the first years.

## Rough costs

These figures are approximate at the time of writing and change with exchange rates, the university and the city:
- **Tuition:** from about US$3,000 a year in mid-sized cities to about US$10,000 or more in Moscow, Saint Petersburg and popular programs.
- **University housing:** among the cheapest options, but quality varies a lot between universities; ask before you apply. Apartments cost more and can be shared with other students.
- **Food:** cooking at home is far cheaper than eating out.
- **Monthly costs:** phone, internet and public transport are relatively affordable.
- **Yearly costs:** visa or residence renewal, and mandatory health insurance.

## Scholarships

Every year the Russian government offers a number of free study places to international students (government quota scholarships), usually applied for through the official Education in Russia portal in coordination with the offices of Russia's cooperation agency. They cover tuition but usually not all housing and living costs. Check dates and conditions on the official site.

