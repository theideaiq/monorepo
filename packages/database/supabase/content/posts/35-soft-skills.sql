    $en$## Hard skills and soft skills

**Hard skills** are the job-specific knowledge: programming for a software developer, accounting for an accountant, design for a designer. They qualify you for the interview.

**Soft skills** are the behaviors that help you work and communicate well with others: how you listen, how you collaborate, how you act under pressure. Think of a doctor who makes time to consult colleagues, treats the nurses with respect and support, and really listens to patients. That doctor builds strong relationships through soft skills, and that's what makes people want to work with them.

Here are three skills worth giving some of your day to.

## 1. Leadership

Leadership isn't reserved for managers or team leads; anyone can learn it. A good leader:

- Motivates and inspires the team consistently.
- Makes decisions that are both fast and effective.
- Solves problems and disagreements before they grow.
- Accepts criticism and learns from it.

Start small: volunteer to organize an event at your school or university, or coordinate a group project.

## 2. Communication

Communication is the key to every other skill, because it lets you send and receive ideas, information and feelings effectively. Confidence, empathy and negotiation all grow out of it. To improve:

- Control your tone and speak clearly.
- Listen with focus, and let the speaker feel they have your full attention.
- Learn body language; it can leave a stronger impression than the words themselves.
- Accept criticism, pick out the constructive parts and act on them.

## 3. Self-motivation

Self-motivation means creating your own drive to finish your work or studies, and getting back up after a setback without waiting for someone to push you. To strengthen it:

- Adapt to different situations and environments without letting your performance slip.
- Think positively: propose solutions instead of complaining, and find the lesson in every experience.
- Be creative: don't repeat the same approach and expect a different result.
- Stay ambitious; every goal you reach sets up a bigger one.
- Commit to your goal and work on it now instead of waiting for "the right moment."
- Talk to yourself positively.

[Time management](/club/time-management) and [effective learning techniques](/club/learn-faster) help turn that drive into results.

## Showing them on your CV and in interviews

Writing "excellent communication skills" on your CV isn't enough. Give an example: an activity you led, a project you coordinated, a problem you solved with your team. In interviews, tell the story briefly: the situation, what you did and the result. To build your professional presence, start with [your first steps online](/club/first-steps-online).

