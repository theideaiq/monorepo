## Step 2: Build a portfolio

Clients want to see what you can do before they pay, so in this world a portfolio matters more than a CV. Create profiles on the platforms that fit your field:

- **Artists and designers:** ArtStation, Behance and Dribbble, plus a work-focused Instagram.
- **Developers:** GitHub (see [your first steps online](/club/first-steps-online)).
- **Writers:** a blog on WordPress or Medium.
- **Everyone:** a tidy LinkedIn profile, and a personal website if you can.

Portfolio tips:

- Publish only your best work, not everything.
- Remove older pieces that no longer reflect your level.
- Enter competitions and challenges (such as ArtStation's); taking part or winning adds weight to your profile.
- No clients yet? Do sample projects that mirror real requests.

## Step 3: Find clients

Create a professional profile on freelance platforms and link your portfolio:

- **Global:** Upwork, Fiverr, Freelancer.com and PeoplePerHour, plus Toptal for experienced professionals.
- **Arabic:** Khamsat and Mostaql.
- **Remote jobs:** LinkedIn Jobs and job boards such as Indeed.

When you're ready to take work, add **Open for Commissions** to your pages so people know you're available.

## Step 4: Set your price

Pricing depends on your field, the hours a job takes and your level. Look at what people at your level charge on the same platform, start reasonably, and raise your rates with every good review and new skill. Always agree in advance on the number of revisions and the delivery date.

## Step 5: Get paid

The big platforms offer several withdrawal methods, including **Payoneer** and, on some platforms, direct bank transfer. Receiving money through PayPal from Iraq is limited or unavailable, so **check which payment services work in Iraq** before you accept a job, along with their fees and how long verification takes. You'll usually need a local bank account to withdraw your money (see [our guide to bank accounts in Iraq](/club/bank-accounts-in-iraq)).

## Protect yourself

- Keep work on the platform where possible; it protects you in a dispute.
- Don't start a big job without a written agreement or an upfront payment.
- Be wary of anyone who asks you to pay a "registration fee" for work, or asks for your full banking details.
- Don't hand over final files before you're paid; send a preview instead.

