## Public and private universities

- **Public universities:** much lower fees but more competition, especially for medical programs that require high grades. They usually ask for an admission test such as YÖS or the SAT.
- **Private (foundation) universities:** higher fees and usually lighter requirements. Many accept your secondary certificate plus a language certificate; some ask for extra tests.

Fees vary widely: from a few hundred dollars a year at some public universities to tens of thousands of dollars for programs like medicine at private ones. They depend on the program, the university, the city and the language of study.

## Admission tests: YÖS and the SAT

- **YÖS:** the admission exam for international students in Türkiye. Each university used to run its own; Türkiye's measurement center ÖSYM then began running a central exam called TR-YÖS. The rules have changed in recent years, so check which test each university on your list accepts.
- **SAT:** many Turkish universities accept it instead of YÖS, but some universities and programs (especially medicine and engineering) may not, or may ask for a high score. Read our [SAT guide](/club/sat-guide).

Some universities admit students on their secondary-school grades alone for certain programs.

## Language of study

- **Turkish:** you'll need a Turkish language certificate such as TÖMER, or whatever the university specifies, or a preparatory language year. Studying in Turkish is usually cheaper than the same program in English.
- **English:** you'll need TOEFL, IELTS or another test the university accepts (see our [IELTS guide](/club/ielts-guide)), or you can pass the university's own English exam or preparatory year.

## Intakes

Unlike in Iraq, many Turkish universities open applications more than once a year: some in spring and summer, some again before the semester starts. Dates differ from one university to another, so follow each university's website.

## Recognition in Iraq

Before you apply, make sure the university and program are recognized by Iraq's Ministry of Higher Education and Scientific Research, and check its conditions (such as a minimum grade for some programs). If you plan to come back and work in Iraq, this matters more than anything else.

## Türkiye Scholarships (Türkiye Bursları)

A fully funded government scholarship covering tuition, housing, a monthly stipend, health insurance, flights and a year of Turkish language study, for bachelor's, master's and PhD. Highlights:
- No language certificate and no YÖS or SAT needed to apply.
- Applications are online and usually open in January and February each year.
- Selection looks at your academic record, volunteering and leadership, and your application answers, followed by an interview for shortlisted candidates.

Start building your record of activities and drafting your answers early; competition is strong.

## Tips

- Ask Iraqi students already studying in Türkiye about their university and housing.
- Compare the full cost: tuition, housing and living, not tuition alone.
- Don't rely on one destination; put Türkiye on a varied list, as in our [study abroad roadmap](/club/study-abroad-roadmap).

