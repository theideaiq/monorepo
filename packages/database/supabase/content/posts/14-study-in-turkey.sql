## منحة الحكومة التركية (Türkiye Bursları)

منحة حكومية ممولة بالكامل تغطي الرسوم والسكن وراتباً شهرياً والتأمين الصحي وتذاكر السفر وسنة لتعلّم التركية، للبكالوريوس والماجستير والدكتوراه. ميزاتها:
- لا تتطلب شهادة لغة ولا اختبار YÖS أو SAT عند التقديم.
- التقديم إلكتروني، ويُفتح عادة في كانون الثاني وشباط من كل سنة.
