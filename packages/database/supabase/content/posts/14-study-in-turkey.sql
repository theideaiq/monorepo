## جامعات حكومية وخاصة

- **الجامعات الحكومية:** رسومها أقل بكثير، لكن المنافسة عليها أعلى، خصوصاً في التخصصات الطبية التي تتطلب معدلاً مرتفعاً. تطلب غالباً نتيجة اختبار قبول مثل YÖS أو SAT.
