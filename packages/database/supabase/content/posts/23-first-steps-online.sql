## 1. ملف على LinkedIn

LinkedIn شبكة اجتماعية للعمل والدراسة والفرص. فيها تبني شبكة علاقاتك المهنية (Networking)، ويصبح ملفك سيرة ذاتية حية على الإنترنت.

- أنشئ ملفك على الموقع أو التطبيق، واختر صورة واضحة ومهنية.
- اكتب عنواناً مختصراً عنك، مثل "طالب إعدادية مهتم بالبرمجة والتصميم".
- أضف مدرستك أو جامعتك، وأنشطتك التطوعية، والدورات التي أكملتها، وبرامج التبادل التي شاركت فيها.
- تواصل مع زملائك ومدرّسيك والأشخاص الذين تعرّفت عليهم في الأنشطة والبرامج.

املأ الملف بعناية. فكّر فيه كواجهتك أمام أي جهة تريد أن تعرفك.

## 2. بريد إلكتروني احترافي

إذا كان بريدك مليئاً بالأرقام والألقاب التي اخترتها قبل سنوات، فقد حان وقت بريد جديد. أنشئ بريداً على Gmail باسمك الحقيقي، مثل الاسم الأول والأخير، واستخدمه لكل ما هو رسمي: الجامعات والمنح والعمل.

وإذا أحببت خطوة أبعد، فيمكنك شراء نطاق باسمك (مثل yourname.com) وربط بريد احترافي به. هذه مهارة مفيدة بحد ذاتها، وتستطيع أن تبني عليها موقعك الشخصي لاحقاً.

## 3. حساب على GitHub وتعلّم Git

Git أداة لإدارة المشاريع تحفظ نسخة من كل تغيير في عملك، وGitHub موقع تستضيف عليه مشاريعك وتشاركها مع زملائك. هما أساسيان لكل من يعمل في البرمجة، ومفيدان لأصحاب الاهتمامات التقنية والإبداعية عموماً.

- أنشئ ملفك على GitHub.
- تعلّم أساسيات Git مجاناً من [The Odin Project](https://www.theodinproject.com).
- انشر مشاريعك الصغيرة، حتى البسيطة منها. مع الوقت يصبح ملفك على GitHub معرض أعمالك.

لمزيد من الموارد، اقرأ [دليل تطوير المواقع](/club/web-development).

## 4. سيرة ذاتية مرتّبة

بدون سيرة ذاتية يصعب أن تقدّم على أي شيء تقريباً: وظيفة، تدريب، برنامج، وأحياناً جامعة تريد أن تعرف مهاراتك وأنشطتك. اكتب سيرتك الآن، وحدّثها كلما أنجزت شيئاً.

اعرف الفرق بين ثلاث وثائق:

- **السيرة الذاتية الكاملة (CV):** من عدة صفحات، تعرض تاريخك الدراسي والمهني وأنشطتك بالكامل.
- **السيرة المختصرة (Résumé):** صفحة أو صفحتان، مفصّلة على وظيفة أو فرصة محددة، تبرز المهارات والخبرات التي تطلبها.
- **رسالة التغطية (Cover Letter):** صفحة ترافق الوثيقتين، تشرح فيها اهتمامك بالفرصة ولماذا تناسبك.

يمكنك البدء بقوالب جاهزة من [Canva](https://www.canva.com/resumes/templates/). وملف LinkedIn لا يغني عن السيرة الذاتية، حتى لو أمكن توليد سيرة منه؛ احتفظ دائماً بنسخة مكتوبة إلكترونية وورقية.

وإذا كنت تقنياً، فموقع شخصي بسيط تعرض فيه أعمالك وسيرتك سيترك انطباعاً ممتازاً.

