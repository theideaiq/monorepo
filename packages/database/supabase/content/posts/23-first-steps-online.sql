    $en$Most opportunities start online now: universities search your name, organizations ask for a link to your profile and employers want your CV. Here are four steps we recommend every student take now, not on application day.

## 1. A LinkedIn profile

LinkedIn is a social network for work, study and opportunities. It's where you build your professional network, and your profile becomes a living CV online.

- Create a profile on the website or app, with a clear, professional photo.
- Write a short headline, like "High school student interested in programming and design."
- Add your school or university, volunteering, courses you've completed and exchange programs you've joined.
- Connect with classmates, teachers and people you meet through activities and programs.

Fill it in carefully. Think of it as your front page for anyone who wants to know you.

## 2. A professional email address

If your email address is full of numbers and nicknames you picked years ago, it's time for a new one. Create a Gmail address with your real name, such as your first and last name, and use it for everything official: universities, scholarships and work.

If you want to go further, you can buy a domain with your name (like yourname.com) and set up a professional email on it. It's a useful skill in itself, and you can build a personal website on it later.

## 3. GitHub, and learning Git

Git is a tool that tracks every change in your project, and GitHub is a website where you host your projects and share them with others. Both are essential for anyone in programming and useful for technical and creative people in general.

- Create your GitHub profile.
- Learn the basics of Git for free with [The Odin Project](https://www.theodinproject.com).
- Publish your small projects, even simple ones. Over time your GitHub becomes your portfolio.

For more resources, read [the web development guide](/club/web-development).

## 4. A well-organized CV

Without a CV it's hard to apply for almost anything: a job, an internship, a program, and sometimes a university that wants to know your skills and activities. Write yours now and update it whenever you achieve something.

Know the difference between three documents:

- **CV (curriculum vitae):** several pages covering your full academic and professional history and activities.
- **Résumé:** one or two pages tailored to a specific job or opportunity, highlighting the skills and experience it asks for.
- **Cover letter:** a page that accompanies them, explaining your interest in the opportunity and why you're a good fit.

You can start from ready-made templates on [Canva](https://www.canva.com/resumes/templates/). A LinkedIn profile doesn't replace a CV, even if you can generate one from it; always keep a written copy, digital and printed.

If you're technical, a simple personal website showing your work and CV makes an excellent impression.

