#!/usr/bin/env bun
/**
 * Runs before every `cap sync` (`bun run cap:sync`): writes
 * `native/www/shell.js`, which tells the bundled offline screen where the
 * website lives and gives it its Arabic and English text from the messages
 * files.
 * The file is generated (git-ignored); offline.html still works without it.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import ar from "@repo/internationalization/messages/ar.json" with {
  type: "json",
};
import en from "@repo/internationalization/messages/en.json" with {
  type: "json",
};
import { resolveServerUrl } from "../capacitor.config";

export const shellScript = (url: string) =>
  `// Generated by native/prepare.ts. Do not edit.\nwindow.IDEA_SHELL = ${JSON.stringify(
    {
      messages: { ar: ar.app.native.offline, en: en.app.native.offline },
      url,
    },
    null,
    2
  )};\n`;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { url, isLiveReload } = resolveServerUrl(process.env);
  writeFileSync(new URL("www/shell.js", import.meta.url), shellScript(url));
  console.log(`The IDEA shell → ${url}${isLiveReload ? " (live reload)" : ""}`);
}
